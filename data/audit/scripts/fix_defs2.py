hit = 0
miss = set(NEW.keys())
for f in sorted(os.listdir(BASE)):
    if not (f.startswith("cards_") and f.endswith(".jsonl")):
        continue
    p = os.path.join(BASE, f)
    rows = []
    changed = 0
    with io.open(p, encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                o = json.loads(line)
                w = o.get("word", "")
                if w in NEW and len(o.get("definition", "")) < 15:
                    o["definition"] = NEW[w]
                    changed += 1
                    miss.discard(w)
                rows.append(o)
    if changed:
        with io.open(p, "w", encoding="utf-8", newline="\n") as fh:
            for o in rows:
                fh.write(json.dumps(o, ensure_ascii=False, separators=(",", ":")) + "\n")
        print(f"{f}: 修改 {changed} 条")
        hit += changed
print(f"共修改 {hit} 条；未匹配到（可能已改或不存在）：{sorted(miss) if miss else '无'}")

